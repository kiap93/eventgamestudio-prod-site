/**
 * Generate a unique ID with a readable prefix
 */
function uid(prefix: string): string {
  const rand = Math.random().toString(36).substring(2, 8);
  const time = Date.now().toString(36).substring(4);
  return `${prefix}-${rand}${time}`;
}

/**
 * Deep clone an element tree and assign fresh, unique IDs to every node
 */
export function cloneElementsWithFreshIds(elements: ResultScreenElement[]): ResultScreenElement[] {
  return elements.map((item) => {
    const newId = uid(item.type);
    if (item.type === 'card') {
      const card = item as ResultCardElement;
      return {
        ...card,
        id: newId,
        children: cloneElementsWithFreshIds(card.children || []),
      } as ResultCardElement;
    }
    if (item.type === 'group') {
      const group = item as ResultGroupElement;
      return {
        ...group,
        id: newId,
        children: cloneElementsWithFreshIds(group.children || []),
      } as ResultGroupElement;
    }
    return {
      ...item,
      id: newId,
    };
  });
}

