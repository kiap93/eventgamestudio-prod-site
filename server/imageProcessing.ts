import { Window } from 'happy-dom';
import sharp from 'sharp';
import {
  FileValidationResult,
  FileValidationOptions,
  toUint8Array,
  detectFileFormat,
  isSvgContent,
} from './fileValidation.js';

export interface SvgSanitizationResult {
  valid: boolean;
  error?: string;
  code?: string;
  sanitizedSvg?: string;
}

/**
 * Parses and strictly sanitizes SVG content using happy-dom (XML DOMParser).
 * Rejects scripts, event-handler attributes, embedded HTML (foreignObject),
 * external resources, XML entities (XXE), and active content.
 */
export function sanitizeAndAuditSvg(svgText: string): SvgSanitizationResult {
  // 1. Strict XXE & external DOCTYPE entity checks
  if (
    /<!ENTITY/i.test(svgText) ||
    /<!DOCTYPE[^>]*SYSTEM/i.test(svgText) ||
    /<!DOCTYPE[^>]*PUBLIC/i.test(svgText)
  ) {
    return {
      valid: false,
      error: 'XML entity declarations (XXE) and external DOCTYPE definitions are strictly forbidden.',
      code: 'SVG_XXE_FORBIDDEN',
    };
  }

  // 2. Parse SVG as XML using happy-dom DOMParser
  let doc: any;
  try {
    const win = new Window();
    const parser = new win.DOMParser();
    doc = parser.parseFromString(svgText, 'image/svg+xml');
  } catch (err: any) {
    return {
      valid: false,
      error: `Malformed SVG: XML parser failed to parse content (${err.message || 'Syntax error'}).`,
      code: 'MALFORMED_SVG',
    };
  }

  // Check for parser errors generated by DOMParser
  const parseError = doc.querySelector('parsererror');
  if (parseError) {
    return {
      valid: false,
      error: `Malformed SVG: ${parseError.textContent?.trim() || 'XML syntax parsing error.'}`,
      code: 'MALFORMED_SVG',
    };
  }

  // 3. Root element check
  const root = doc.documentElement;
  if (!root || root.tagName.toLowerCase() !== 'svg') {
    return {
      valid: false,
      error: 'Invalid SVG: Root element must be an <svg> tag.',
      code: 'INVALID_SVG_ROOT',
    };
  }

  // 4. Forbidden elements: scripts, embedded objects, external frames, HTML wrappers
  const forbiddenTags = new Set([
    'script',
    'foreignobject',
    'iframe',
    'object',
    'embed',
    'applet',
    'frame',
    'frameset',
    'link',
    'meta',
    'base',
    'audio',
    'video',
    'source',
    'track',
    'form',
    'input',
    'button',
    'textarea',
    'select',
    'option',
    'canvas',
  ]);

  const allElements = [root, ...Array.from(root.querySelectorAll('*'))];

  for (const el of allElements) {
    const tag = el.tagName.toLowerCase();

    if (forbiddenTags.has(tag)) {
      return {
        valid: false,
        error: `Forbidden SVG element detected: <${tag}>. Active scripts, external embeds, and embedded HTML are prohibited.`,
        code: 'SVG_SECURITY_VIOLATION',
      };
    }

    // Inspect style elements for malicious CSS expressions or external imports
    if (tag === 'style') {
      const cssContent = el.textContent || '';
      if (
        /@import/i.test(cssContent) ||
        /expression\s*\(/i.test(cssContent) ||
        /behavior\s*:/i.test(cssContent) ||
        /-moz-binding\s*:/i.test(cssContent) ||
        /javascript\s*:/i.test(cssContent) ||
        /url\s*\(\s*['"]?\s*(https?:|\/\/|javascript:)/i.test(cssContent)
      ) {
        return {
          valid: false,
          error: 'Dangerous CSS rules (@import, expression, external URLs) detected in SVG <style> element.',
          code: 'SVG_SECURITY_VIOLATION',
        };
      }
    }

    // Inspect all attributes
    const attrs = Array.from(el.attributes || []) as any[];
    for (const attr of attrs) {
      const attrName = (attr.name || '').toLowerCase();
      const attrVal = (attr.value || '').trim();

      // Disallow inline event handlers (onload, onerror, onclick, etc.)
      if (attrName.startsWith('on')) {
        return {
          valid: false,
          error: `Event handler attribute "${attrName}" is forbidden on SVG element <${tag}>.`,
          code: 'SVG_SECURITY_VIOLATION',
        };
      }

      // Disallow dangerous URI schemes or external references
      if (
        ['href', 'xlink:href', 'src', 'data', 'action', 'formaction', 'poster'].includes(
          attrName
        )
      ) {
        if (/^(javascript:|vbscript:|data:text\/html)/i.test(attrVal)) {
          return {
            valid: false,
            error: `Dangerous script URI scheme in attribute "${attrName}": ${attrVal}`,
            code: 'SVG_SECURITY_VIOLATION',
          };
        }

        // Prohibit external remote references (prevent SSRF and tracking)
        // Note: local hash references like href="#myGradient" or href="#path1" are safe and allowed
        if (/^(https?:|\/\/|ftp:)/i.test(attrVal)) {
          return {
            valid: false,
            error: `External remote resource reference forbidden in attribute "${attrName}": ${attrVal}`,
            code: 'SVG_SECURITY_VIOLATION',
          };
        }
      }

      // Check inline style attribute for CSS expression or javascript:
      if (attrName === 'style') {
        if (
          /expression\s*\(|javascript\s*:|url\s*\(\s*['"]?\s*(https?:|\/\/|javascript:)/i.test(
            attrVal
          )
        ) {
          return {
            valid: false,
            error: `Dangerous inline style attribute on <${tag}>: ${attrVal}`,
            code: 'SVG_SECURITY_VIOLATION',
          };
        }
      }
    }
  }

  // Ensure svg has xml namespace
  if (!root.getAttribute('xmlns')) {
    root.setAttribute('xmlns', 'http://www.w3.org/2000/svg');
  }

  return {
    valid: true,
    sanitizedSvg: root.outerHTML,
  };
}

/**
 * Validates, decodes, checks dimensions, and securely processes uploaded images.
 * - For PNG, JPEG, WEBP: checks magic bytes, decodes via sharp, verifies dimensions and format consistency.
 * - For SVG: parses with happy-dom XML DOMParser, enforces strict security audit, and rasterizes to PNG.
 * - For Cloudflare runtime: rejects SVG with specific explanation message.
 */
export async function validateAndProcessImageUpload(
  buffer: Uint8Array | ArrayBuffer | Buffer | any,
  options: FileValidationOptions = {}
): Promise<FileValidationResult> {
  const bytes = toUint8Array(buffer);

  // 1. Presence check
  if (!bytes || bytes.length === 0) {
    return {
      valid: false,
      error: 'No file uploaded or file is empty',
      code: 'NO_FILE_UPLOADED',
    };
  }

  // 2. File size limit
  const maxBytes = options.maxSizeBytes || 25 * 1024 * 1024; // Default 25MB
  if (bytes.length > maxBytes) {
    const maxMb = (maxBytes / (1024 * 1024)).toFixed(1);
    const actualMb = (bytes.length / (1024 * 1024)).toFixed(1);
    return {
      valid: false,
      error: `File size exceeds maximum allowed limit of ${maxMb}MB (${actualMb}MB provided).`,
      code: 'FILE_TOO_LARGE',
    };
  }

  const rawName = (options.originalName || '').trim();
  const dotIndex = rawName.lastIndexOf('.');
  const ext = dotIndex !== -1 ? rawName.slice(dotIndex).toLowerCase() : '';
  const declaredMime = (options.declaredMime || 'application/octet-stream').toLowerCase().trim();

  // 3. Binary magic bytes / file signature detection (PNG, JPEG, WEBP, MP3, etc.)
  const detected = detectFileFormat(bytes);

  if (detected) {
    // If genuine binary content is renamed with .svg extension or SVG MIME type, reject as spoofing
    if (ext === '.svg' || declaredMime === 'image/svg+xml' || declaredMime === 'image/svg') {
      return {
        valid: false,
        error: `File extension "${ext}" does not match detected file content (${detected.format}).`,
        code: 'MIME_EXTENSION_MISMATCH',
      };
    }

    // Verify allowed media types (image, audio, video)
    if (options.allowedMediaTypes && !options.allowedMediaTypes.includes(detected.mediaType)) {
      return {
        valid: false,
        error: `File type "${detected.mediaType}" (${detected.format}) is not allowed in this category. Allowed types: ${options.allowedMediaTypes.join(', ')}.`,
        code: 'MEDIA_TYPE_NOT_ALLOWED',
      };
    }

    // Verify allowed specific formats
    if (options.allowedFormats && !options.allowedFormats.includes(detected.format)) {
      return {
        valid: false,
        error: `File format "${detected.format}" is not allowed. Allowed formats: ${options.allowedFormats.join(', ')}.`,
        code: 'UNSUPPORTED_FILE_TYPE',
      };
    }

    // Enforce consistency between extension and detected format
    if (ext) {
      const isIsobmffCompatible =
        (detected.format === 'MP4' && ext === '.mov') ||
        (detected.format === 'MOV' && ext === '.mp4');

      if (!detected.allowedExtensions.includes(ext) && !isIsobmffCompatible) {
        return {
          valid: false,
          error: `File extension "${ext}" does not match detected file content (${detected.format}).`,
          code: 'MIME_EXTENSION_MISMATCH',
        };
      }
    }

    // Enforce consistency between declared MIME type and detected format
    if (declaredMime && declaredMime !== 'application/octet-stream') {
      const isMimeAllowed = detected.allowedMimes.includes(declaredMime);
      const isIsobmffMime =
        (detected.format === 'MP4' && declaredMime === 'video/quicktime') ||
        (detected.format === 'MOV' && declaredMime === 'video/mp4');

      if (!isMimeAllowed && !isIsobmffMime) {
        return {
          valid: false,
          error: `Declared MIME type "${declaredMime}" does not match detected file content (${detected.format}).`,
          code: 'MIME_EXTENSION_MISMATCH',
        };
      }
    }

    // For raster images (PNG, JPEG, WEBP): decode via sharp and verify integrity
    if (detected.mediaType === 'image') {
      try {
        const meta = await sharp(bytes).metadata();

        // Check format mismatch between sharp decode and magic bytes
        const detectedFormatLower = detected.format.toLowerCase();
        const sharpFormatLower = (meta.format || '').toLowerCase();

        // Normalize jpg/jpeg
        const isFormatMatch =
          sharpFormatLower === detectedFormatLower ||
          (detectedFormatLower === 'jpeg' && sharpFormatLower === 'jpg') ||
          (detectedFormatLower === 'jpg' && sharpFormatLower === 'jpeg');

        if (!isFormatMatch) {
          return {
            valid: false,
            error: `Decoded image format (${meta.format}) does not match detected binary signature (${detected.format}).`,
            code: 'MIME_EXTENSION_MISMATCH',
          };
        }

        // Check dimensions
        const maxWidth = options.maxWidth || 4096;
        const maxHeight = options.maxHeight || 4096;

        if (!meta.width || !meta.height || meta.width <= 0 || meta.height <= 0) {
          return {
            valid: false,
            error: 'Image dimensions are invalid or zero.',
            code: 'CORRUPTED_FILE',
          };
        }

        if (meta.width > maxWidth || meta.height > maxHeight) {
          return {
            valid: false,
            error: `Image dimensions (${meta.width}x${meta.height}) exceed maximum allowed dimensions (${maxWidth}x${maxHeight}).`,
            code: 'DIMENSIONS_EXCEEDED',
          };
        }

        return {
          valid: true,
          format: detected.format,
          mediaType: detected.mediaType,
          mimeType: detected.canonicalMime,
          extension: ext || detected.canonicalExtension,
          fileSize: bytes.length,
          processedBuffer: bytes,
          width: meta.width,
          height: meta.height,
        };
      } catch (decodeErr: any) {
        return {
          valid: false,
          error: `Malformed or corrupted ${detected.format} image: ${decodeErr.message || 'Unable to decode image header/data'}`,
          code: 'CORRUPTED_FILE',
        };
      }
    }

    // Non-image formats (audio/video)
    return {
      valid: true,
      format: detected.format,
      mediaType: detected.mediaType,
      mimeType: detected.canonicalMime,
      extension: ext || detected.canonicalExtension,
      fileSize: bytes.length,
      processedBuffer: bytes,
    };
  }

  // 4. Non-binary files: Check for SVG content
  const isSvg =
    ext === '.svg' ||
    declaredMime === 'image/svg+xml' ||
    declaredMime === 'image/svg' ||
    declaredMime === 'application/xml+svg' ||
    isSvgContent(bytes);

  if (isSvg) {
    // If SVG conversion is not allowed in this context (e.g. showcase uploads)
    if (options.allowSvg === false) {
      return {
        valid: false,
        error: 'SVG uploads are not permitted for security reasons. Please upload raster images (PNG, JPEG, WEBP).',
        code: 'SVG_NOT_ALLOWED',
      };
    }

    // Check for disguised SVG (e.g. malicious SVG named "photo.png" or "photo.jpg")
    if (ext && ext !== '.svg') {
      return {
        valid: false,
        error: `File content is SVG but declared extension is "${ext}". File renaming/spoofing is forbidden.`,
        code: 'MIME_EXTENSION_MISMATCH',
      };
    }

    if (
      declaredMime &&
      declaredMime !== 'application/octet-stream' &&
      !['image/svg+xml', 'image/svg', 'application/xml+svg'].includes(declaredMime)
    ) {
      return {
        valid: false,
        error: `Declared MIME type "${declaredMime}" does not match detected SVG content.`,
        code: 'MIME_EXTENSION_MISMATCH',
      };
    }

    // If running in edge runtime without native sharp / libvips support
    if (options.isEdgeRuntime) {
      return {
        valid: false,
        error: 'SVG conversion is unavailable in this runtime environment. Please upload a raster image (PNG, JPEG, or WEBP).',
        code: 'SVG_CONVERSION_UNAVAILABLE',
      };
    }

    // Enforce SVG-specific file size limit (5MB max for vector markup)
    const svgMaxBytes = Math.min(maxBytes, 5 * 1024 * 1024);
    if (bytes.length > svgMaxBytes) {
      return {
        valid: false,
        error: `SVG file exceeds maximum allowed limit of 5MB (${(bytes.length / (1024 * 1024)).toFixed(1)}MB provided).`,
        code: 'FILE_TOO_LARGE',
      };
    }

    const svgText = new TextDecoder('utf-8', { fatal: false }).decode(bytes);

    // Sanitize and audit SVG DOM tree
    const audit = sanitizeAndAuditSvg(svgText);
    if (!audit.valid) {
      return {
        valid: false,
        error: audit.error || 'SVG security check failed.',
        code: (audit.code as any) || 'SVG_SECURITY_VIOLATION',
      };
    }

    // Rasterize validated SVG to high-quality PNG
    try {
      const sanitizedBuffer = Buffer.from(audit.sanitizedSvg || svgText);
      const targetSize = 512; // Crisp resolution suitable for Match-3 tile sprites & retina displays

      const pngBuffer = await sharp(sanitizedBuffer)
        .resize({
          width: targetSize,
          height: targetSize,
          fit: 'inside',
          withoutEnlargement: true,
        })
        .png({ compressionLevel: 8 })
        .toBuffer();

      const meta = await sharp(pngBuffer).metadata();
      const width = meta.width || targetSize;
      const height = meta.height || targetSize;

      return {
        valid: true,
        format: 'PNG',
        mediaType: 'image',
        mimeType: 'image/png',
        extension: '.png',
        fileSize: pngBuffer.length,
        processedBuffer: pngBuffer,
        originalFormat: 'SVG',
        width,
        height,
      };
    } catch (rasterErr: any) {
      return {
        valid: false,
        error: `Failed to rasterize SVG into safe image: ${rasterErr.message || 'Image processing error'}. Ensure the SVG contains valid geometry and viewBox.`,
        code: 'CORRUPTED_FILE',
      };
    }
  }

  // 5. Neither detected binary format nor SVG
  const allowedListDesc = options.allowedFormats
    ? options.allowedFormats.join(', ')
    : 'PNG, JPEG, WEBP, MP3, WAV, OGG, MP4, WEBM, MOV';
  return {
    valid: false,
    error: `Unsupported file signature. The file content does not match any allowed format (${allowedListDesc}).`,
    code: 'UNSUPPORTED_FILE_TYPE',
  };
}
